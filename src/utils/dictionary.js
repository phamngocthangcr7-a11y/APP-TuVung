/**
 * Tự động tạo câu ví dụ TOEIC chuẩn xác theo từ và loại từ (Fallback 100% không bao giờ để trống)
 */
export const getToeicExampleFallback = (rawWord, pos = 'noun', meaning = '') => {
  const cleanWord = (rawWord || '').trim();
  if (!cleanWord) return { example: '', translation: '' };

  const lowerWord = cleanWord.toLowerCase();

  // 1. Nếu có trong bộ ví dụ TOEIC ETS tinh tuyển
  if (CURATED_TOEIC_EXAMPLES[lowerWord]) {
    return CURATED_TOEIC_EXAMPLES[lowerWord];
  }

  // Tách lấy nghĩa ngắn gọn đầu tiên để lồng vào câu tiếng Việt
  const firstMeaning = (meaning || cleanWord).split(/[,;/]/)[0].trim() || cleanWord;
  const cleanPos = (pos || 'noun').toLowerCase();

  // 2. Mẫu câu TOEIC chuyên nghiệp theo loại từ
  if (cleanPos.includes('adj')) {
    return {
      example: `The management recognized that the new procedure was highly ${cleanWord} for the company.`,
      translation: `Ban quản lý ghi nhận rằng quy trình mới rất ${firstMeaning} đối với công ty.`
    };
  }

  if (cleanPos.includes('verb')) {
    return {
      example: `All department heads will meet next Monday to ${cleanWord} the updated corporate guidelines.`,
      translation: `Tất cả trưởng bộ phận sẽ họp vào thứ Hai tới để ${firstMeaning} các hướng dẫn cập nhật của công ty.`
    };
  }

  if (cleanPos.includes('adv')) {
    return {
      example: `Quarterly profits and customer satisfaction rates have increased ${cleanWord} this fiscal year.`,
      translation: `Lợi nhuận theo quý và mức độ hài lòng của khách hàng đã tăng ${firstMeaning} trong năm tài chính này.`
    };
  }

  if (cleanPos.includes('phr') || cleanWord.includes(' ')) {
    return {
      example: `All staff members are strictly instructed to ${cleanWord} throughout the operational review.`,
      translation: `Toàn bộ nhân viên được hướng dẫn nghiêm ngặt phải ${firstMeaning} trong suốt đợt đánh giá vận hành.`
    };
  }

  // Mặc định Danh từ (Noun)
  return {
    example: `The committee submitted a comprehensive report on the ${cleanWord} to the board of directors.`,
    translation: `Ủy ban đã nộp một báo cáo toàn diện về ${firstMeaning} lên hội đồng quản trị.`
  };
};

/**
 * Tra cứu từ vựng tiếng Anh: Lấy phiên âm IPA, loại từ, nghĩa tiếng Việt chuẩn, và ví dụ TOEIC
 */
export const lookupEnglishWord = async (rawWord) => {
  const word = (rawWord || '').trim();
  if (!word) {
    return { found: false, error: 'Vui lòng nhập từ vựng tiếng Anh' };
  }

  const result = {
    word,
    phonetic: '',
    partOfSpeech: word.includes(' ') ? 'phr' : 'noun',
    meaning: '',
    allMeanings: [],
    example: '',
    exampleTranslation: '',
    found: false
  };

  // 1. Kiểm tra kho ví dụ chuẩn trước
  const curated = CURATED_TOEIC_EXAMPLES[word.toLowerCase()];
  if (curated) {
    result.example = curated.example;
    result.exampleTranslation = curated.translation;
  }

  try {
    // 2. Tra nghĩa tiếng Việt qua Google Translate Single API
    const transUrl = `https://translate.googleapis.com/translate_a/single?client=gtx&sl=en&tl=vi&dt=t&dt=bd&q=${encodeURIComponent(word)}`;
    const transRes = await fetch(transUrl);
    if (transRes.ok) {
      const transData = await transRes.json();
      
      const primaryTrans = transData[0]?.[0]?.[0] || '';
      result.meaning = primaryTrans;

      if (transData[1] && Array.isArray(transData[1])) {
        const meaningsList = [];
        transData[1].forEach(item => {
          const pos = item[0] || '';
          if (!result.partOfSpeech || result.partOfSpeech === 'noun') {
            if (pos === 'verb') result.partOfSpeech = 'verb';
            else if (pos === 'adjective') result.partOfSpeech = 'adj';
            else if (pos === 'adverb') result.partOfSpeech = 'adv';
          }
          const wordsForPos = item[1] || [];
          meaningsList.push(...wordsForPos.slice(0, 4));
        });
        result.allMeanings = Array.from(new Set([primaryTrans, ...meaningsList])).filter(Boolean);
        if (result.allMeanings.length > 0) {
          result.meaning = result.allMeanings.slice(0, 3).join(', ');
        }
      } else {
        result.allMeanings = [primaryTrans];
      }
      result.found = true;
    }
  } catch (err) {
    console.warn('Google Translate API lookup failed:', err);
  }

  try {
    // 3. Tra phiên âm IPA và câu ví dụ từ Free Dictionary API (cho từ đơn)
    if (!word.includes(' ')) {
      const dictUrl = `https://api.dictionaryapi.dev/api/v2/entries/en/${encodeURIComponent(word)}`;
      const dictRes = await fetch(dictUrl);
      if (dictRes.ok) {
        const dictData = await dictRes.json();
        const entry = dictData[0];
        if (entry) {
          result.phonetic = entry.phonetic || entry.phonetics?.find(p => p.text)?.text || '';
          
          const meaningObj = entry.meanings?.[0];
          if (meaningObj?.partOfSpeech) {
            const pos = meaningObj.partOfSpeech.toLowerCase();
            if (pos.includes('verb')) result.partOfSpeech = 'verb';
            else if (pos.includes('adj')) result.partOfSpeech = 'adj';
            else if (pos.includes('adv')) result.partOfSpeech = 'adv';
            else if (pos.includes('noun')) result.partOfSpeech = 'noun';
          }

          if (!result.example) {
            for (const m of entry.meanings || []) {
              for (const def of m.definitions || []) {
                if (def.example) {
                  result.example = def.example;
                  break;
                }
              }
              if (result.example) break;
            }
          }
        }
      }
    }
  } catch (err) {
    console.warn('Free Dictionary API lookup failed:', err);
  }

  // 4. Nếu vẫn chưa có câu ví dụ, tìm qua Tatoeba API (Kho câu mẫu song ngữ)
  if (!result.example) {
    try {
      const tatoebaUrl = `https://tatoeba.org/en/api_v0/search?from=eng&to=vie&query=${encodeURIComponent(word)}`;
      const tatoebaRes = await fetch(tatoebaUrl);
      if (tatoebaRes.ok) {
        const tatoebaData = await tatoebaRes.json();
        const match = tatoebaData.results?.find(r => r.text?.toLowerCase().includes(word.toLowerCase()));
        if (match && match.text) {
          result.example = match.text;
          const viTrans = match.translations?.[0]?.[0]?.text;
          if (viTrans) result.exampleTranslation = viTrans;
        }
      }
    } catch (e) {
      console.warn('Tatoeba search failed:', e);
    }
  }

  // 5. Nếu vẫn chưa có câu ví dụ, áp dụng tự động TOEIC Fallback Generator (ĐẢM BẢO LUÔN CÓ CÂU VÍ DỤ!)
  if (!result.example) {
    const fallback = getToeicExampleFallback(word, result.partOfSpeech, result.meaning);
    result.example = fallback.example;
    if (!result.exampleTranslation) {
      result.exampleTranslation = fallback.translation;
    }
  }

  // 6. Dịch câu ví dụ nếu có câu mà chưa có bản dịch
  if (result.example && !result.exampleTranslation) {
    try {
      const exTransUrl = `https://translate.googleapis.com/translate_a/single?client=gtx&sl=en&tl=vi&dt=t&q=${encodeURIComponent(result.example)}`;
      const exRes = await fetch(exTransUrl);
      if (exRes.ok) {
        const exData = await exRes.json();
        result.exampleTranslation = exData[0]?.[0]?.[0] || '';
      }
    } catch (e) {
      // ignore
    }
  }

  return result;
};

/**
 * Kiểm tra xem nghĩa người dùng nhập có khớp với nghĩa chuẩn từ điển không
 */
export const checkUserMeaningAccuracy = (userMeaning, dictionaryResult) => {
  if (!userMeaning || !userMeaning.trim()) {
    return {
      status: 'empty',
      message: 'Chưa có nghĩa để đối chiếu. Bạn có thể sử dụng nghĩa gợi ý từ điển bên dưới.',
      isAccurate: false
    };
  }

  const userWords = userMeaning.toLowerCase().replace(/[,;./]/g, ' ').split(/\s+/).filter(Boolean);
  const dictMeanings = (dictionaryResult.allMeanings || [dictionaryResult.meaning || ''])
    .map(m => m.toLowerCase());

  let matchFound = false;
  let matchedTerm = '';

  for (const dm of dictMeanings) {
    const dmClean = dm.toLowerCase();
    for (const uw of userWords) {
      if (uw.length >= 2 && dmClean.includes(uw)) {
        matchFound = true;
        matchedTerm = dm;
        break;
      }
    }
    if (matchFound) break;
  }

  if (matchFound) {
    return {
      status: 'good',
      message: `Rất chuẩn xác! Nghĩa bạn dịch khớp với từ điển: "${matchedTerm}".`,
      isAccurate: true,
      suggestedMeaning: dictionaryResult.meaning
    };
  } else {
    return {
      status: 'warning',
      message: `Nghĩa bạn nhập có thể khác với từ điển thông dụng ("${dictionaryResult.meaning}"). Hãy kiểm tra lại xem có đúng ngữ cảnh TOEIC không nhé!`,
      isAccurate: false,
      suggestedMeaning: dictionaryResult.meaning
    };
  }
};
